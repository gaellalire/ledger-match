//! NBGL user interface: home screen, match result review, address review.

use alloc::format;
use alloc::string::String;
use alloc::vec::Vec;

use crate::match_result::MatchResult;
use crate::AppSW;
use ledger_device_sdk::include_gif;
use ledger_device_sdk::io::Comm;
use ledger_device_sdk::nbgl::{
    Field, NbglAddressReview, NbglGlyph, NbglHomeAndSettings, NbglReview,
};

/// Glyph used in review screens.
#[cfg(any(target_os = "stax", target_os = "flex"))]
const MATCH_GLYPH: NbglGlyph =
    NbglGlyph::from_include(include_gif!("icons/match_64x64.gif", NBGL));
#[cfg(any(target_os = "nanosplus", target_os = "nanox"))]
const MATCH_GLYPH: NbglGlyph =
    NbglGlyph::from_include(include_gif!("icons/match_14x14.gif", NBGL));

/// Home screen glyph: on Nano S+/X it is the masked, inverted PNG generated by
/// build.rs; on Stax/Flex the plain 64x64 glyph.
#[cfg(any(target_os = "stax", target_os = "flex"))]
const HOME_GLYPH: NbglGlyph =
    NbglGlyph::from_include(include_gif!("icons/match_64x64.gif", NBGL));
#[cfg(any(target_os = "nanosplus", target_os = "nanox"))]
const HOME_GLYPH: NbglGlyph =
    NbglGlyph::from_include(include_gif!("glyphs/home_nano_nbgl.png", NBGL));

/// Max characters shown for a players list in the review; longer lists are
/// truncated with an ellipsis (all players are still covered by the signature).
const MAX_PLAYERS_DISPLAY: usize = 96;

/// Application home screen.
pub fn ui_menu_main(_: &mut Comm) -> NbglHomeAndSettings {
    NbglHomeAndSettings::new()
        .glyph(&HOME_GLYPH)
        .infos(
            "Match Signer",
            env!("CARGO_PKG_VERSION"),
            env!("CARGO_PKG_AUTHORS"),
        )
}

/// Display the signer address (derived from the public key) for verification.
pub fn ui_display_address(comm: &mut Comm, addr: &[u8]) -> Result<bool, AppSW> {
    // Display only the last 20 bytes of the address hash.
    const DISPLAY_ADDR_BYTES_LEN: usize = 20;
    let addr_hex = format!(
        "0x{}",
        hex::encode(&addr[addr.len() - DISPLAY_ADDR_BYTES_LEN..]).to_uppercase()
    );

    Ok(NbglAddressReview::new()
        .glyph(&MATCH_GLYPH)
        .review_title("Verify signer address")
        .show(comm, &addr_hex))
}

fn join_truncated(players: &[String], max: usize) -> String {
    let mut s = players.join(", ");
    if s.len() > max {
        let mut end = max;
        while !s.is_char_boundary(end) {
            end -= 1;
        }
        s.truncate(end);
        s.push('…');
    }
    s
}

/// Display a match result for clear signing; returns true if the user
/// approved it.
pub fn ui_display_match(comm: &mut Comm, m: &MatchResult) -> Result<bool, AppSW> {
    let date = m.date_string();
    let score = m.score_string();
    let winner_players = join_truncated(&m.winner.players, MAX_PLAYERS_DISPLAY);
    let loser_players = join_truncated(&m.loser.players, MAX_PLAYERS_DISPLAY);
    let sport = m.sport.clone().unwrap_or_default();

    let mut fields: Vec<Field> = Vec::with_capacity(7);
    if m.sport.is_some() {
        fields.push(Field {
            name: "Sport",
            value: sport.as_str(),
        });
    }
    fields.push(Field {
        name: "Date",
        value: date.as_str(),
    });
    fields.push(Field {
        name: "Winner",
        value: m.winner.name.as_str(),
    });
    if !winner_players.is_empty() {
        fields.push(Field {
            name: "Winner players",
            value: winner_players.as_str(),
        });
    }
    fields.push(Field {
        name: "Loser",
        value: m.loser.name.as_str(),
    });
    if !loser_players.is_empty() {
        fields.push(Field {
            name: "Loser players",
            value: loser_players.as_str(),
        });
    }
    fields.push(Field {
        name: "Score",
        value: score.as_str(),
    });

    let review: NbglReview = NbglReview::new()
        .titles("Review match result", "", "Sign match result")
        .glyph(&MATCH_GLYPH);

    Ok(review.show(comm, &fields))
}
