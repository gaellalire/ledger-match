//! NBGL user interface: home screen, result review, address review.

use alloc::format;
use alloc::string::String;
use alloc::vec::Vec;

use crate::match_result::{Layout, MatchResult, Outcome};
use crate::AppSW;
use ledger_device_sdk::include_gif;
use ledger_device_sdk::io::Comm;
use ledger_device_sdk::nbgl::{
    Field, NbglAddressReview, NbglGlyph, NbglHomeAndSettings, NbglReview,
};

/// Glyph used in review screens.
#[cfg(any(target_os = "stax", target_os = "flex"))]
const MATCH_GLYPH: NbglGlyph =
    NbglGlyph::from_include(include_gif!("icons/match_64x64.gif", NBGL));
#[cfg(any(target_os = "nanosplus", target_os = "nanox"))]
const MATCH_GLYPH: NbglGlyph =
    NbglGlyph::from_include(include_gif!("icons/match_14x14.gif", NBGL));

/// Home screen glyph: on Nano S+/X it is the masked, inverted PNG generated by
/// build.rs; on Stax/Flex the plain 64x64 glyph.
#[cfg(any(target_os = "stax", target_os = "flex"))]
const HOME_GLYPH: NbglGlyph =
    NbglGlyph::from_include(include_gif!("icons/match_64x64.gif", NBGL));
#[cfg(any(target_os = "nanosplus", target_os = "nanox"))]
const HOME_GLYPH: NbglGlyph =
    NbglGlyph::from_include(include_gif!("glyphs/home_nano_nbgl.png", NBGL));

/// Max characters shown for a names list in the review; longer lists are
/// truncated with an ellipsis (all names are still covered by the signature).
const MAX_LIST_DISPLAY: usize = 96;

/// Application home screen.
pub fn ui_menu_main(_: &mut Comm) -> NbglHomeAndSettings {
    NbglHomeAndSettings::new()
        .glyph(&HOME_GLYPH)
        .tagline("Review and sign game results.")
        .infos(
            "Game Signer",
            env!("CARGO_PKG_VERSION"),
            env!("CARGO_PKG_AUTHORS"),
        )
}

/// Display the signer address (derived from the public key) for verification.
pub fn ui_display_address(comm: &mut Comm, addr: &[u8]) -> Result<bool, AppSW> {
    // Display only the last 20 bytes of the address hash.
    const DISPLAY_ADDR_BYTES_LEN: usize = 20;
    let addr_hex = format!(
        "0x{}",
        hex::encode(&addr[addr.len() - DISPLAY_ADDR_BYTES_LEN..]).to_uppercase()
    );

    Ok(NbglAddressReview::new()
        .glyph(&MATCH_GLYPH)
        .review_title("Verify signer address")
        .show(comm, &addr_hex))
}

fn join_truncated(names: &[String], max: usize) -> String {
    let mut s = names.join(", ");
    if s.len() > max {
        let mut end = max;
        while !s.is_char_boundary(end) {
            end -= 1;
        }
        s.truncate(end);
        s.push('…');
    }
    s
}

fn push_opt<'a>(fields: &mut Vec<Field<'a>>, name: &'a str, value: &'a str) {
    if !value.is_empty() {
        fields.push(Field { name, value });
    }
}

/// Display a result for clear signing; returns true if the user approved it.
pub fn ui_display_match(comm: &mut Comm, m: &MatchResult) -> Result<bool, AppSW> {
    let date = m.date_string();
    let activity = m.activity.clone().unwrap_or_default();
    let location = m.location.clone().unwrap_or_default();
    let competition = m.competition.clone().unwrap_or_default();
    let side1 = m.side1.clone().unwrap_or_default();
    let side2 = m.side2.clone().unwrap_or_default();
    let score = m.score_string();
    let referees = join_truncated(&m.referees, MAX_LIST_DISPLAY);
    let side1_players = join_truncated(&m.side1_players, MAX_LIST_DISPLAY);
    let side2_players = join_truncated(&m.side2_players, MAX_LIST_DISPLAY);

    let is_ffa = m.layout() == Layout::FreeForAll;

    // Display name of a side in the result line: side name, else its player
    // list, else a generic label.
    let side_display = |name: &str, players: &str, fallback: &str| -> String {
        if !name.is_empty() {
            String::from(name)
        } else if !players.is_empty() {
            String::from(players)
        } else {
            String::from(fallback)
        }
    };
    let side1_display = side_display(&side1, &side1_players, "Side 1");
    let side2_display = side_display(&side2, &side2_players, "Side 2");

    // Outcome line, deduced from the forfeit field and the score.
    let result_line = match m.outcome() {
        Outcome::Side1Wins => format!("{} beats {}", side1_display, side2_display),
        Outcome::Side2Wins => format!("{} beats {}", side2_display, side1_display),
        Outcome::Draw => format!("Draw between {} and {}", side1_display, side2_display),
        Outcome::Side1WinsByForfeit => format!("{} won by forfeit", side1_display),
        Outcome::Side2WinsByForfeit => format!("{} won by forfeit", side2_display),
        Outcome::BothForfeited => String::from("Both sides forfeited"),
        Outcome::Unknown => String::new(),
    };

    // Individual scores for free-for-all (kept alive until after the review).
    let mut participant_scores: Vec<String> = Vec::new();
    if is_ffa {
        for p in &m.participants {
            participant_scores.push(match p.score {
                Some(s) => format!("{}", s),
                None => String::from("–"),
            });
        }
    }

    let mut fields: Vec<Field> = Vec::new();
    push_opt(&mut fields, "Activity", activity.as_str());
    fields.push(Field {
        name: "Date",
        value: date.as_str(),
    });
    push_opt(&mut fields, "Location", location.as_str());
    push_opt(&mut fields, "Competition", competition.as_str());

    if is_ffa {
        for (i, p) in m.participants.iter().enumerate() {
            fields.push(Field {
                name: p.name.as_str(),
                value: participant_scores[i].as_str(),
            });
        }
        push_opt(&mut fields, "Referees", referees.as_str());
    } else {
        push_opt(&mut fields, "Side 1", side1.as_str());
        push_opt(&mut fields, "Side 2", side2.as_str());
        push_opt(&mut fields, "Score", score.as_str());
        push_opt(&mut fields, "Result", result_line.as_str());
        push_opt(&mut fields, "Referees", referees.as_str());
        push_opt(&mut fields, "Side 1 players", side1_players.as_str());
        push_opt(&mut fields, "Side 2 players", side2_players.as_str());
    }

    let review: NbglReview = NbglReview::new()
        .titles(
            if is_ffa {
                "Review result"
            } else {
                "Review game result"
            },
            "",
            if is_ffa { "Sign result" } else { "Sign game result" },
        )
        .glyph(&MATCH_GLYPH);

    Ok(review.show(comm, &fields))
}
